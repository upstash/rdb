const (
	fracMask  uint64 = 0x000fffffffffffff
	expMask   uint64 = 0x7ff0000000000000
	hiddenBit uint64 = 0x0010000000000000
	signMask  uint64 = 0x8000000000000000
	expBias          = 1023 + 52

	firstPower = -348
	stepShift  = 3
	stepPowers = 1 << stepShift
	expMax     = -32
	expMin     = -60
)

type Fp struct {
	frac uint64
	exp  int
}

