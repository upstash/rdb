// Dtoa returns the exact representation Redis's fpconv_dtoa selects.
func Dtoa(value float64) string {
	var dest [64]byte
	length := 0
	negative := math.Float64bits(value)&signMask != 0
	if negative {
		dest[length] = '-'
		length++
	}

	if specialLength := filterSpecial(value, dest[length:]); specialLength != 0 {
		return string(dest[:length+specialLength])
	}
	// Fast path: values on the two-decimal grid are common in practice, and
	// grisu2 already prints them in fixed notation, so emit that directly.
	// The upper bound is not arbitrary: from 1e8 on, grisu2 switches integral
	// values to scientific notation ("1e+8"), which this path cannot produce.
	magnitude := math.Abs(value)
	if magnitude >= 1 && magnitude < 1e7 {
		if fixedLength := emitFixedTwoDecimals(magnitude, dest[length:]); fixedLength != 0 {
			return string(dest[:length+fixedLength])
		}
	}

	var digits [18]byte
	k := 0
	digitCount := grisu2(value, digits[:], &k)
	length += emitDigits(digits[:digitCount], dest[length:], k, negative)

	return string(dest[:length])
}

func emitFixedTwoDecimals(value float64, dest []byte) int {
	// Reconstructing the value rules out nearby binary floats whose
	// multiplication by 100 merely rounds to an integer.
	scaledValue := value * 100
	scaled := uint64(scaledValue)
	if scaledValue != float64(scaled) || float64(scaled)/100 != value {
		return 0
	}

	whole, fraction := scaled/100, scaled%100
	length := len(strconv.AppendUint(dest[:0], whole, 10))
	if fraction == 0 {
		return length
	}

	dest[length] = '.'
	length++
	dest[length] = byte(fraction/10) + '0'
	length++
	if fraction%10 != 0 {
		dest[length] = byte(fraction%10) + '0'
		length++
	}

	return length
}

func build(value float64) Fp {
	raw := math.Float64bits(value)
	fp := Fp{
		frac: raw & fracMask,
		exp:  int((raw & expMask) >> 52),
	}

	if fp.exp != 0 {
		fp.frac += hiddenBit
		fp.exp -= expBias
	} else {
		fp.exp = -expBias + 1
	}

	return fp
}

func normalize(fp *Fp) {
	for fp.frac&hiddenBit == 0 {
		fp.frac <<= 1
		fp.exp--
	}

	const shift = 64 - 52 - 1
	fp.frac <<= shift
	fp.exp -= shift
}

func normalizedBoundaries(fp Fp) (Fp, Fp) {
	upper := Fp{
		frac: (fp.frac << 1) + 1,
		exp:  fp.exp - 1,
	}

	for upper.frac&(hiddenBit<<1) == 0 {
		upper.frac <<= 1
		upper.exp--
	}

	const upperShift = 64 - 52 - 2
	upper.frac <<= upperShift
	upper.exp -= upperShift

	lowerShift := 1
	if fp.frac == hiddenBit {
		lowerShift = 2
	}
	lower := Fp{
		frac: (fp.frac << lowerShift) - 1,
		exp:  fp.exp - lowerShift,
	}
	lower.frac <<= uint(lower.exp - upper.exp)
	lower.exp = upper.exp

	return lower, upper
}

func multiply(a, b Fp) Fp {
	hi, lo := bits.Mul64(a.frac, b.frac)

	return Fp{
		frac: hi + lo>>63,
		exp:  a.exp + b.exp + 64,
	}
}

func roundDigit(digits []byte, delta, remainder, kappa, fraction uint64) {
	for remainder < fraction && delta-remainder >= kappa &&
		(remainder+kappa < fraction || fraction-remainder > remainder+kappa-fraction) {
		digits[len(digits)-1]--
		remainder += kappa
	}
}

func generateDigits(fp, upper, lower Fp, digits []byte, k *int) int {
	wfraction := upper.frac - fp.frac
	delta := upper.frac - lower.frac
	one := Fp{
		frac: uint64(1) << uint(-upper.exp),
		exp:  upper.exp,
	}
	part1 := upper.frac >> uint(-one.exp)
	part2 := upper.frac & (one.frac - 1)

	index := 0
	kappa := 10
	divIndex := 10
	for kappa > 0 && part1 < tens[divIndex] {
		divIndex++
		kappa--
	}
	for ; kappa > 0; divIndex++ {
		divisor := tens[divIndex]
		digit := part1 / divisor
		digits[index] = byte(digit) + '0'
		index++

		part1 -= digit * divisor
		kappa--

		tmp := (part1 << uint(-one.exp)) + part2
		if tmp <= delta {
			*k += kappa
			roundDigit(digits[:index], delta, tmp, divisor<<uint(-one.exp), wfraction)
			return index
		}
	}

	unitIndex := 18
	for {
		part2 *= 10
		delta *= 10
		kappa--

		digit := part2 >> uint(-one.exp)
		if digit != 0 || index != 0 {
			digits[index] = byte(digit) + '0'
			index++
		}

		part2 &= one.frac - 1
		if part2 < delta {
			*k += kappa
			roundDigit(digits[:index], delta, part2, one.frac, wfraction*tens[unitIndex])
			return index
		}

		unitIndex--
	}
}

func grisu2(value float64, digits []byte, k *int) int {
	w := build(value)
	lower, upper := normalizedBoundaries(w)
	normalize(&w)

	cachedPower, cachedExponent := findCachedPower10(upper.exp)
	w = multiply(w, cachedPower)
	upper = multiply(upper, cachedPower)
	lower = multiply(lower, cachedPower)
	lower.frac++
	upper.frac--
	*k = -cachedExponent

	return generateDigits(w, upper, lower, digits, k)
}

func emitDigits(digits, dest []byte, k int, negative bool) int {
	digitCount := len(digits)
	exponent := absInt(k + digitCount - 1)

	if k >= 0 && exponent < digitCount+7 {
		copy(dest, digits)
		for i := range k {
			dest[digitCount+i] = '0'
		}
		return digitCount + k
	}

	if k < 0 && (k > -7 || exponent < 4) {
		offset := digitCount - absInt(k)
		if offset <= 0 {
			offset = -offset
			dest[0] = '0'
			dest[1] = '.'
			for i := 0; i < offset; i++ {
				dest[2+i] = '0'
			}
			copy(dest[offset+2:], digits)
			return digitCount + 2 + offset
		}

		copy(dest, digits[:offset])
		dest[offset] = '.'
		copy(dest[offset+1:], digits[offset:])
		return digitCount + 1
	}

	maxDigits := 18
	if negative {
		maxDigits--
	}
	if digitCount > maxDigits {
		digitCount = maxDigits
		digits = digits[:digitCount]
	}

	index := 0
	dest[index] = digits[0]
	index++
	if digitCount > 1 {
		dest[index] = '.'
		index++
		copy(dest[index:], digits[1:])
		index += digitCount - 1
	}

	dest[index] = 'e'
	index++
	if k+digitCount-1 < 0 {
		dest[index] = '-'
	} else {
		dest[index] = '+'
	}
	index++

	century := 0
	if exponent > 99 {
		century = exponent / 100
		dest[index] = byte(century) + '0'
		index++
		exponent -= century * 100
	}
	if exponent > 9 {
		decade := exponent / 10
		dest[index] = byte(decade) + '0'
		index++
		exponent -= decade * 10
	} else if century != 0 {
		dest[index] = '0'
		index++
	}

	dest[index] = byte(exponent%10) + '0'
	return index + 1
}

func filterSpecial(value float64, dest []byte) int {
	if value == 0 {
		dest[0] = '0'
		return 1
	}

	raw := math.Float64bits(value)
	if raw&expMask != expMask {
		return 0
	}
	if raw&fracMask != 0 {
		copy(dest, "nan")
	} else {
		copy(dest, "inf")
	}
	return 3
}

func findCachedPower10(exponent int) (Fp, int) {
	const oneLogTen = 0.30102999566398114
	approximation := int(float64(-(exponent + len(powersTen))) * oneLogTen)
	// The numerator stays positive (its range is [33, 664] across every binary
	// exponent), so the shift matches the division the C original performs.
	index := (approximation - firstPower) >> stepShift

	for {
		current := exponent + powersTen[index].exp + 64
		if current < expMin {
			index++
			continue
		}
		if current > expMax {
			index--
			continue
		}

		return powersTen[index], firstPower + index*stepPowers
	}
}

func absInt(x int) int {
	if x < 0 {
		return -x
	}
	return x
}
